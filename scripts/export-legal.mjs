// Generates the public privacy policy and terms pages from the same source
// the app reads (src/data/legal.js), so the offline copy and the hosted copy
// cannot say different things.
//
//   npm run legal:export
//
// Writes public/privacy/index.html and public/terms/index.html. Deploy the
// public/ directory (or copy those two folders) to the address configured in
// EXPO_PUBLIC_PRIVACY_URL / EXPO_PUBLIC_TERMS_URL. Static hosts serve a
// directory at `/privacy`, redirecting to `/privacy/`, which is why the files
// are index.html inside a folder rather than privacy.html.
//
// The pages are self-contained — styles are inline, no fonts or scripts are
// fetched — so they can be dropped on any host, including one with no build
// step.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEGAL_DOCUMENTS } from '../src/data/legal.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE_URL = (process.env.LEGAL_BASE_URL || 'https://qitabe-noor.app').replace(/\/+$/, '');
const SUPPORT_EMAIL = process.env.LEGAL_SUPPORT_EMAIL || 'support@qitabe-noor.app';

const escapeHtml = value => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const renderSections = doc => doc.sections.map(section => `
      <section>
        <h2>${escapeHtml(section.title)}</h2>
${(section.paragraphs || []).map(p => `        <p>${escapeHtml(p)}</p>`).join('\n')}
${section.bullets?.length ? `        <ul>
${section.bullets.map(b => `          <li>${escapeHtml(b)}</li>`).join('\n')}
        </ul>` : ''}
      </section>`).join('\n');

const otherDoc = id => (id === 'privacy' ? LEGAL_DOCUMENTS.terms : LEGAL_DOCUMENTS.privacy);
const otherPath = id => `${BASE_URL}/${id === 'privacy' ? 'terms' : 'privacy'}/`;

const renderPage = doc => `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(doc.title)} — Qitab-e-Noor</title>
  <meta name="description" content="${escapeHtml(doc.summary)}">
  <meta name="color-scheme" content="light">
  <!-- Generated by scripts/export-legal.mjs from src/data/legal.js.
       Edit the data, then run: npm run legal:export -->
  <style>
    :root {
      --bg: #FBFAF7;
      --card: #FFFFFF;
      --ink: #1F2420;
      --muted: #5C655F;
      --gold: #8A620F;
      --emerald: #046C4E;
      --line: #E4E1D8;
    }
    * { box-sizing: border-box; }
    body {
      margin: 0;
      background: var(--bg);
      color: var(--ink);
      font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      -webkit-text-size-adjust: 100%;
    }
    header {
      background: var(--emerald);
      color: #fff;
      padding: 28px 20px 24px;
    }
    header .wrap { max-width: 760px; margin: 0 auto; }
    header .brand { font-size: 20px; font-weight: 800; letter-spacing: -0.3px; }
    header .tagline { color: rgba(255,255,255,0.78); font-size: 13px; margin-top: 2px; }
    main { max-width: 760px; margin: 0 auto; padding: 32px 20px 56px; }
    h1 { font-size: 30px; line-height: 1.2; margin: 0 0 6px; letter-spacing: -0.5px; }
    .updated { color: var(--muted); font-size: 13px; margin: 0 0 24px; }
    .summary {
      background: var(--card);
      border: 1px solid var(--line);
      border-left: 4px solid var(--gold);
      border-radius: 10px;
      padding: 16px 18px;
      margin: 0 0 8px;
      color: var(--ink);
    }
    section { margin-top: 28px; }
    h2 { color: var(--gold); font-size: 18px; margin: 0 0 8px; }
    p { margin: 0 0 12px; }
    ul { margin: 0 0 12px; padding-left: 22px; }
    li { margin-bottom: 8px; }
    footer {
      border-top: 1px solid var(--line);
      margin-top: 40px;
      padding-top: 20px;
      color: var(--muted);
      font-size: 13px;
      line-height: 1.6;
    }
    footer a { color: var(--emerald); }
    .links { display: flex; flex-wrap: wrap; gap: 16px; margin-bottom: 10px; }
    a { color: var(--emerald); }
    @media (prefers-color-scheme: dark) {
      :root {
        --bg: #111312;
        --card: #171B19;
        --ink: #ECEFEA;
        --muted: #9AA39C;
        --gold: #C9A44C;
        --emerald: #34D399;
        --line: #2A322D;
      }
      header { background: #0F7A55; color: #fff; }
    }
    @media print {
      header { background: none; color: #000; padding: 0 0 12px; }
      body { background: #fff; }
      a { color: #000; }
    }
  </style>
</head>
<body>
  <header>
    <div class="wrap">
      <div class="brand">Qitab-e-Noor</div>
      <div class="tagline">Your Spiritual Companion</div>
    </div>
  </header>
  <main>
    <h1>${escapeHtml(doc.title)}</h1>
    <p class="updated">Last updated ${escapeHtml(doc.updated)}</p>
    <p class="summary">${escapeHtml(doc.summary)}</p>
${renderSections(doc)}
    <footer>
      <div class="links">
        <a href="${otherPath(doc.id)}">${escapeHtml(otherDoc(doc.id).title)}</a>
        <a href="${BASE_URL}/">Open Qitab-e-Noor</a>
        <a href="mailto:${SUPPORT_EMAIL}">${SUPPORT_EMAIL}</a>
      </div>
      <p>The same text is available inside the app at Settings &rarr; Legal &amp; Privacy, so it can be read without a connection.</p>
    </footer>
  </main>
</body>
</html>
`;

for (const doc of Object.values(LEGAL_DOCUMENTS)) {
  const dir = join(ROOT, 'public', doc.id);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, 'index.html'), renderPage(doc), 'utf8');
  console.log(`wrote public/${doc.id}/index.html`);
}

console.log(`Base URL: ${BASE_URL}`);
