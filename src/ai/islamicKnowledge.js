/**
 * Search used by the topic browser. It matches partial text against the topic
 * and its keywords, then falls back to the same canonical vocabulary retrieval
 * uses — so "roza", "namaz" and "zakaat" find the right area even though those
 * spellings are not listed as keywords.
 */
export const topicMatchesQuery = (item, query) => {
  const needle = normaliseText(query);
  if (!needle) return true;

  // Word-prefix matching lets "taha" find Tahajjud without matching letters
  // buried inside an unrelated word ("riba" inside "tribalism").
  const queryWords = needle.split(' ');
  const itemWords = [
    ...new Set([
      ...normaliseText(item.topic).split(' '),
      ...item.keywords.flatMap(keyword => normaliseText(keyword).split(' ')),
    ]),
  ];
  if (queryWords.every(word => itemWords.some(candidate => candidate.startsWith(word)))) {
    return true;
  }

  const queryTokens = [...new Set(tokenise(query))];
  if (!queryTokens.length) return false;
  const itemTokens = new Set(tokenise([item.topic, ...item.keywords].join(' ')));
  return queryTokens.every(token => itemTokens.has(token));
};

