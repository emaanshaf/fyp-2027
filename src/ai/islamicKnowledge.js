/** Lowercase, drop punctuation, collapse whitespace. */
const normaliseText = value => String(value || '')
  .toLowerCase()
  .replace(/[’']/g, '')
  .replace(/[^a-z0-9\s]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

/** A deliberately light stemmer — enough to align prayers/praying/prayed. */
const stem = word => {
  if (word.length > 5 && word.endsWith('ies')) return `${word.slice(0, -3)}y`;
  if (word.length > 5 && word.endsWith('ing')) return word.slice(0, -3);
  if (word.length > 4 && word.endsWith('ed')) return word.slice(0, -2);
  if (word.length > 4 && word.endsWith('es')) return word.slice(0, -2);
  if (word.length > 3 && word.endsWith('s') && !word.endsWith('ss')) return word.slice(0, -1);
  return word;
};

const canonicalToken = word => {
  const lower = word.toLowerCase();
  if (SYNONYMS[lower]) return SYNONYMS[lower];
  const base = stem(lower);
  return SYNONYMS[base] || base;
};

const tokenise = text => normaliseText(text)
  .split(' ')
  .filter(Boolean)
  .filter(word => !STOP_WORDS.has(word))
  .map(canonicalToken)
  .filter(word => word.length >= 2);

const containsPhrase = (haystack, phrase) =>
  Boolean(phrase) && ` ${haystack} `.includes(` ${phrase} `);

// Pre-compute the token view of every entry once. With 100+ entries this is
// invisible at module load and keeps each keystroke cheap.
const INDEXED = KNOWLEDGE_BASE.map(entry => {
  const keywordPhrases = entry.keywords.map(normaliseText).filter(Boolean);
  return {
    entry,
    keywordPhrases,
    topicPhrase: normaliseText(entry.topic),
    keywordTokens: new Set(keywordPhrases.flatMap(p => tokenise(p))),
    topicTokens: new Set(tokenise(entry.topic)),
  };
});

// The general "Halal & Haram" overview shares vocabulary with most practical
// questions. It should be the fallback, never the winner over a dedicated
// topic such as "Smoking, Vaping & Drugs" or "Islamic Finance in Practice".
const GENERIC_TOPICS = new Set(['Halal & Haram']);
const GENERIC_TOPIC_PENALTY = 12;

const scoreEntry = (indexed, paddedQuery, queryTokens) => {
  const { entry, keywordPhrases, topicPhrase, keywordTokens, topicTokens } = indexed;
  let score = 0;

  const querySet = new Set(queryTokens);
  const matchedCanonicalPhrases = new Set();

  for (const phrase of keywordPhrases) {
    if (containsPhrase(paddedQuery, phrase)) {
      // Whole phrases are strong evidence; longer phrases are more specific.
      score += 20 + phrase.split(' ').length * 10;
      matchedCanonicalPhrases.add(phrase);
    }
  }

  // A phrase can also be matched through its canonical tokens, so
  // "sunnah prayers" still reaches a "sunnah prayer" keyword and
  // "fast if i am sick" reaches "fast if sick". Each distinct token set is
  // counted once, so listing five spellings of one idea cannot inflate a score.
  const covered = new Set();
  for (const phrase of keywordPhrases) {
    if (matchedCanonicalPhrases.has(phrase)) continue;
    const tokens = [...new Set(tokenise(phrase))];
    if (tokens.length < 2 || tokens.length > 5) continue;
    if (!tokens.every(token => querySet.has(token))) continue;

    const key = [...tokens].sort().join(' ');
    if (covered.has(key)) continue;
    covered.add(key);
    score += 20 + tokens.length * 5;
  }

  // "Tell me about Music & Entertainment" should always open that exact topic.
  if (containsPhrase(paddedQuery, topicPhrase)) score += 50;

  for (const token of queryTokens) {
    if (keywordTokens.has(token)) score += 6;
    else if (token.length >= 4 && [...keywordTokens].some(k => k.startsWith(token))) score += 3;
    if (topicTokens.has(token)) score += 2;
  }

  if (GENERIC_TOPICS.has(entry.topic) && score > 0) score -= GENERIC_TOPIC_PENALTY;
  return score;
};

const MIN_SCORE = 6;

/**
 * Ranked retrieval used both for offline answers and as RAG grounding for the
 * live assistant. Returns [{ entry, score }] ordered best-first.
 */
export const searchKnowledgeBase = (question, topN = 3) => {
  if (!question || !question.trim()) return [];
  const paddedQuery = ` ${normaliseText(question)} `;
  const queryTokens = [...new Set(tokenise(question))];

  return INDEXED
    .map(indexed => ({ entry: indexed.entry, score: scoreEntry(indexed, paddedQuery, queryTokens) }))
    .filter(result => result.score >= MIN_SCORE)
    .sort((a, b) => b.score - a.score)
    .slice(0, topN);
};

export const queryAI = question => {
  const [top] = searchKnowledgeBase(question, 1);
  return top ? top.entry : null;
};

/**
 * Topic names that share vocabulary with `topic`, for follow-up chips.
 * Generic overlap is fine here — it is a prompt, not a ruling.
 */
export const relatedTopics = (topic, limit = 3) => {
  const source = INDEXED.find(item => item.entry.topic === topic);
  if (!source) return [];
  const sourceWords = new Set([...source.keywordTokens, ...source.topicTokens]);

  return INDEXED
    .filter(item => item.entry.topic !== topic)
    .map(item => {
      const words = new Set([...item.keywordTokens, ...item.topicTokens]);
      let overlap = 0;
      for (const word of words) if (sourceWords.has(word)) overlap += 1;
      return { topic: item.entry.topic, overlap };
    })
    .filter(item => item.overlap > 0)
    .sort((a, b) => b.overlap - a.overlap)
    .slice(0, limit)
    .map(item => item.topic);
};

